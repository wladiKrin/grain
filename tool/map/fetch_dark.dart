// Fetches OpenFreeMap's Dark style into lib/map/openfreemap_dark.g.dart, the
// copy Grain lifts the contrast of (see strongerDark in map_styles.dart).
//
//   dart run tool/map/fetch_dark.dart
import 'dart:convert';
import 'dart:io';

Future<void> main() async {
  const url = 'https://tiles.openfreemap.org/styles/dark';
  final client = HttpClient()..userAgent = 'Grain build tool';
  final response = await (await client.getUrl(Uri.parse(url))).close();
  if (response.statusCode != 200) {
    stderr.writeln('$url: HTTP ${response.statusCode}');
    exit(1);
  }
  final style = jsonDecode(await response.transform(utf8.decoder).join());
  client.close();
  final json = const JsonEncoder.withIndent(' ').convert(style);
  File('lib/map/openfreemap_dark.g.dart').writeAsStringSync(
    '// GENERATED by tool/map/fetch_dark.dart from $url: do not edit.\n'
    '// OpenFreeMap Dark (from OpenMapTiles Dark Matter: BSD-3-Clause code,\n'
    '// CC-BY 4.0 design).\n'
    '// ignore_for_file: lines_longer_than_80_chars\n\n'
    "const openFreeMapDarkJson = r'''\n$json\n''';\n",
  );
}
